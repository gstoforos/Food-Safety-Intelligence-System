VERSION = "2026-09-14"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    if not (args.write or args.check):
        ap.error("pass --write or --check")

    targets = [(GS_PATH, render_gs()), (HTML_PATH, render_html())]
    stale = []
    for path, want in targets:
        have = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if have == want:
            continue
        stale.append(path)
        if args.write:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "w", encoding="utf-8") as fh:
                fh.write(want)

    rel = [os.path.relpath(p, ROOT) for p in stale]
    if args.write:
        print("wrote: " + (", ".join(rel) if rel else "(nothing — already current)"))
        return 0
    if stale:
        print("STALE: " + ", ".join(rel))
        print("run: python3 tools/gen_alert_vocab.py --write")
        return 1
    print("alert vocabulary is in sync")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
