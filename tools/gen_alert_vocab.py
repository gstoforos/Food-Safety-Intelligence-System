BEGIN = "// ===== GENERATED BY tools/gen_alert_vocab.py — DO NOT EDIT BY HAND ====="
END = "// ===== END GENERATED ====="


def js(value) -> str:
    return json.dumps(value, ensure_ascii=False)


def _js_map(name: str, mapping: dict) -> str:
    lines = ["var %s = {" % name]
    for k, v in mapping.items():
        lines.append("  %s: %s," % (js(k), js(v)))
    lines.append("};")
    return "\n".join(lines)


def _js_array(name: str, values: list) -> str:
    out, cur = [], "  "
    for v in values:
        item = js(v) + ", "
        if len(cur) + len(item) > 76:
            out.append(cur.rstrip())
            cur = "  "
        cur += item
    if cur.strip():
        out.append(cur.rstrip().rstrip(","))
    return "var %s = [\n%s\n];" % (name, "\n".join(out))


# ---------------------------------------------------------------------------
# docs/alerts.html
# ---------------------------------------------------------------------------

def html_block() -> str:
    def arr(name, values):
        out, cur = [], "  "
        for v in values:
            item = js(v) + ","
            if len(cur) + len(item) > 74:
                out.append(cur.rstrip())
                cur = "  "
            cur += item + " "
        if cur.strip():
            out.append(cur.rstrip().rstrip(","))
        return "const %s = [\n%s\n];" % (name, "\n".join(out))

    return "\n".join([
        BEGIN,
        "// Source of truth: tools/alert_vocab.py. Every word below is a key the",
        "// Apps Script matcher (AftsAlertVocab.gs) holds an explicit token list",
        "// for, so a word offered here is a word the backend understands.",
        "// Regenerate with: python3 tools/gen_alert_vocab.py --write",
        arr("PATHOGENS", list(V.PATHOGEN.keys())),
        "",
        arr("PRODUCTS", list(V.PRODUCT.keys())),
        "",
        arr("COUNTRIES", list(V.COUNTRY)),
        END,
    ])


def render_html() -> str:
    src = open(HTML_PATH, encoding="utf-8").read()
    block = html_block()

    if BEGIN in src and END in src:
        head, rest = src.split(BEGIN, 1)
        _, tail = rest.split(END, 1)
        return head + block + tail

    # First run: replace the three hand-written arrays and their lead comments.
    pat = re.compile(
        r"// Pathogens: aligned with.*?^\];\s*\n",
        re.S | re.M,
    )
    start = src.find("// ===== Reference pools =====")
    if start < 0:
        raise SystemExit("alerts.html: '// ===== Reference pools =====' not found")
    end_marker = "// Seed brand suggestions from the dashboard's dataset when available."
    end = src.find(end_marker)
    if end < 0:
        raise SystemExit("alerts.html: brand-seed comment not found")
    return (src[:start]
            + "// ===== Reference pools =====\n"
            + block + "\n\n"
            + src[end:])


