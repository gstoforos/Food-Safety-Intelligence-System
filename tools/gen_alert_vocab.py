def render_gs() -> str:
    parts = [GS_HEADER, BEGIN, ""]
    parts.append("var FSIS_VOCAB_VERSION = %s;" % js(VERSION))
    parts.append("")
    parts.append(_js_map("PATHOGEN_VOCAB", V.PATHOGEN))
    parts.append("")
    parts.append(_js_map("PRODUCT_VOCAB", V.PRODUCT))
    parts.append("")
    parts.append(_js_array("COUNTRY_LIST", V.COUNTRY))
    parts.append("")
    parts.append(_js_map("COUNTRY_ALIASES", V.COUNTRY_ALIASES))
    parts.append("")
    parts.append(_js_map("PATHOGEN_LEGACY", V.PATHOGEN_LEGACY))
    parts.append("")
    parts.append(_js_map("RETIRED_PATHOGEN", V.RETIRED_PATHOGEN))
    parts.append("")
    parts.append(_js_map("RETIRED_PRODUCT", V.RETIRED_PRODUCT))
